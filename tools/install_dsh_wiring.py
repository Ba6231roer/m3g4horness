"""
install_dsh_wiring — idempotently wire the mgh dsh profile assets into a dsh profile's
`cordis.patch.yml` (the dsh analog of install_hook.py / install_opencode_plugin.py).

dsh does NOT auto-discover project-local hook configuration, so the shim must be mounted
through the profile layer: a marker-anchored managed block appending one loader `insert`
entry whose `name` is the absolute path of the mirrored shim (the loader turns path-shaped
names into file:// URLs; verified against dsh 0.1.5-rc.2 — plugin loading from a plain
absolute .ts path works under the shipped node runtime).

With `--delegates-file` (the mgh profile composition face), the SAME managed block also
carries the named delegation instances (one dsh-tool-subagent insert entry per stage,
generated by tools/gen_dsh_tiers.py from releases/dsh/agents/) and the timeout policy
rows (`tool-bash`/`tool-pwsh` `enableRunInBackground: false` — headless units get no
background-job promotion channel; the guard's JobCtl deny stays the backstop). Without
the flag the block is the shim mount alone (unchanged legacy shape).

Idempotent: the block is delimited by `mgh-guard-wiring begin/end` comment markers. A
second run whose block content is current reports `present` (no rewrite); a stale block
(points at an old path / older asset set) is replaced IN PLACE between the markers;
everything OUTSIDE the markers (the user's own patch entries) is never touched.

CLI (`--help` is the contract surface):
  py install_dsh_wiring.py --patch-file <path> --shim <abs-path-to-mgh-guard.ts>
                           [--delegates-file <generated-delegates.yml>] [--remove]

Precondition (fail-loud, no partial write): the profile directory containing --patch-file
MUST already exist (dsh creates profiles itself; the installer NEVER silently invents one).

stdout (R5.3b): {"patch_file":"...","action":"written|present|replaced|removed|absent","shim":"..."}
stderr = diagnostics. Exit codes (R5.3b): 0 ok · 1 IO/precondition error · 2 misuse.

Build/install-time tool (peer of tools/install_hook.py); NOT an /mgh-* orchestrator.
Zero runtime deps (Python >=3.10 stdlib: argparse/json/sys/pathlib).
"""
from __future__ import annotations
import argparse
import json
import sys
from pathlib import Path

BEGIN = "# mgh-guard-wiring begin (managed by install.sh --dsh; do not edit inside)"
END = "# mgh-guard-wiring end"

# Timeout policy (mgh profile composition face, spike-pinned to dsh 0.1.5-rc.2):
# close the model's explicit background-job channel on both shell tools, so a
# timed-out unit is deadline-killed with no hidden promoted job left alive
# (fan-out runtime contract 超时合同). Guard JobCtl deny remains the backstop.
TIMEOUT_ROWS = (
    "- id: tool-bash\n"
    "  config:\n"
    "    enableRunInBackground: false\n"
    "- id: tool-pwsh\n"
    "  config:\n"
    "    enableRunInBackground: false\n"
)


def _delegates_rows(path: Path) -> str:
    """Load the generated delegates fragment (one `- insert:` dsh-tool-subagent
    entry per named stage instance). Comments (the generator's provenance
    header) are stripped — it cites build-repo paths that are dead inside a
    user profile; the entry rows themselves are embedded VERBATIM (they are
    generated from releases/dsh/agents/, same-source discipline)."""
    text = path.read_text(encoding="utf-8")
    rows = "\n".join(ln for ln in text.splitlines() if not ln.startswith("#"))
    rows = rows.strip("\n")
    if not rows.lstrip().startswith("- insert:"):
        print(f"error: delegates fragment is not a patch-entry list "
              f"(expected `- insert:` rows): {path}", file=sys.stderr)
        sys.exit(2)
    return rows + "\n"


def _block(shim: str, delegates: str | None = None) -> str:
    # One loader patch entry: insert a plugin whose name is the absolute shim
    # path. json.dumps gives a valid YAML double-quoted scalar (Windows
    # backslashes safe). With delegates present the block additionally carries
    # the timeout policy + the named delegation instances (mgh profile face).
    out = (
        f"{BEGIN}\n"
        f"- insert:\n"
        f"    - id: mgh-guard\n"
        f"      name: {json.dumps(shim, ensure_ascii=False)}\n"
    )
    if delegates is not None:
        out += TIMEOUT_ROWS + delegates
    out += f"{END}\n"
    return out


def _split_existing(text: str):
    """Return (pre, block_or_None, post) around our managed block (first occurrence)."""
    lines = text.splitlines(keepends=True)
    start = end = -1
    for i, line in enumerate(lines):
        if start == -1 and line.rstrip("\r\n") == BEGIN:
            start = i
        elif start != -1 and line.rstrip("\r\n") == END:
            end = i
            break
    if start == -1 or end == -1:
        return text, None, ""
    return "".join(lines[:start]), "".join(lines[start:end + 1]), "".join(lines[end + 1:])


def main():
    ap = argparse.ArgumentParser(
        description="idempotently wire mgh-guard dsh shim into a profile cordis.patch.yml")
    ap.add_argument("--patch-file", required=True,
                    help="path to the profile's cordis.patch.yml (its directory must exist)")
    ap.add_argument("--shim", required=True,
                    help="ABSOLUTE path to the mirrored mgh-guard.ts (must be a .ts path)")
    ap.add_argument("--delegates-file",
                    help="generated named-delegation fragment (gen_dsh_tiers.py "
                         "--delegates-out); when given, the managed block also "
                         "carries the timeout policy + one dsh-tool-subagent "
                         "instance per stage (mgh profile composition face)")
    ap.add_argument("--remove", action="store_true",
                    help="remove our managed block instead of wiring it")
    args = ap.parse_args()

    patch = Path(args.patch_file)
    shim = args.shim

    if args.remove:
        if not patch.is_file():
            print(json.dumps({"patch_file": str(patch), "action": "absent", "shim": shim}))
            return 0
        pre, block, post = _split_existing(patch.read_text(encoding="utf-8"))
        if block is None:
            print(f"[install_dsh_wiring] no managed block in {patch}", file=sys.stderr)
            print(json.dumps({"patch_file": str(patch), "action": "absent", "shim": shim}))
            return 0
        patch.write_text(pre + post, encoding="utf-8")
        print(f"[install_dsh_wiring] removed managed wiring from {patch}", file=sys.stderr)
        print(json.dumps({"patch_file": str(patch), "action": "removed", "shim": shim}))
        return 0

    if not shim.strip():
        print("error: --shim must be a non-empty absolute path", file=sys.stderr)
        return 2
    if not Path(shim).is_absolute():
        print(f"error: --shim must be ABSOLUTE (dsh loader anchors bare names to node "
              f"resolution, not the patch dir): {shim}", file=sys.stderr)
        return 2

    # Precondition, checked BEFORE any write (fail-loud, never half-wired): the profile
    # directory must exist (dsh owns profile creation).
    prof_dir = patch.parent
    if not prof_dir.is_dir():
        print(f"error: profile directory not found: {prof_dir}\n"
              f"  dsh creates profiles itself — boot the profile once (e.g. "
              f"`dsh --profile {prof_dir.name}`) or create it with "
              f"`dsh --profile {prof_dir.name} --from-default-profile web`, then re-run "
              f"the installer.", file=sys.stderr)
        return 1

    delegates = (_delegates_rows(Path(args.delegates_file))
                 if args.delegates_file else None)
    wanted = _block(shim, delegates)
    if patch.is_file():
        text = patch.read_text(encoding="utf-8")
        pre, block, post = _split_existing(text)
        if block is not None and block.rstrip("\r\n") + "\n" == wanted:
            action = "present"
        elif block is not None:
            patch.write_text(pre + wanted + post, encoding="utf-8")
            action = "replaced"  # stale path (moved install) — swapped in place
        else:
            sep = "" if (not text or text.endswith("\n")) else "\n"
            patch.write_text(text + sep + wanted, encoding="utf-8")
            action = "written"
    else:
        patch.write_text(wanted, encoding="utf-8")
        action = "written"

    print(f"[install_dsh_wiring] {patch}: {action}", file=sys.stderr)
    print(json.dumps({"patch_file": str(patch), "action": action, "shim": shim},
                     ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
