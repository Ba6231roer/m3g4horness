"""install_dsh_wiring.py idempotent profile wiring (add-mgh-dsh-host-foundation task 5.4;
dsh analog of test_install_hook / test_install_opencode_plugin).

Asserts: fresh wire appends the managed block; double-run is `present` (byte-stable);
the user's own patch entries are preserved untouched; a stale block is replaced in place
(not duplicated); --remove takes the block out keeping user content; a missing profile
directory fails loud (exit 1, nothing written); a relative --shim is misuse (exit 2).
Run: py tests/test_install_dsh.py
"""
import importlib.util, io, json, contextlib, sys, tempfile, unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOOLS = HERE.parent / "tools"


def _load():
    spec = importlib.util.spec_from_file_location("install_dsh_wiring",
                                                  TOOLS / "install_dsh_wiring.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


class TestInstallDshWiring(unittest.TestCase):
    def setUp(self):
        self.m = _load()
        self.d = Path(tempfile.mkdtemp(prefix="mgh_idw_"))
        self.prof = self.d / "profiles" / "web"
        self.prof.mkdir(parents=True)
        self.patch = self.prof / "cordis.patch.yml"
        self.shim = "C:\\target\\mgh-core\\dsh\\mgh-guard.ts"

    def _run(self, patch=None, shim=None, remove=False):
        argv = ["install_dsh_wiring.py",
                "--patch-file", str(patch or self.patch),
                "--shim", shim if shim is not None else self.shim]
        if remove:
            argv.append("--remove")
        old, sys.argv = sys.argv, argv
        out = io.StringIO()
        try:
            with contextlib.redirect_stdout(out), contextlib.redirect_stderr(io.StringIO()):
                code = self.m.main()
        finally:
            sys.argv = old
        return code, out.getvalue().strip()

    def test_fresh_wire_writes_block(self):
        self.patch.write_text("[]\n", encoding="utf-8")
        code, line = self._run()
        self.assertEqual(code, 0)
        self.assertEqual(json.loads(line)["action"], "written")
        text = self.patch.read_text(encoding="utf-8")
        self.assertIn("mgh-guard-wiring begin", text)
        self.assertIn("id: mgh-guard", text)
        self.assertIn(self.shim.replace("\\", "\\\\"), text)  # json-quoted abs path
        self.assertTrue(text.startswith("[]"), "user content kept before the block")

    def test_double_run_is_present_and_stable(self):
        self._run()
        before = self.patch.read_bytes()
        code, line = self._run()
        self.assertEqual(code, 0)
        self.assertEqual(json.loads(line)["action"], "present")
        self.assertEqual(self.patch.read_bytes(), before)  # no duplicate, no rewrite

    def test_stale_block_replaced_in_place(self):
        self._run()
        code, line = self._run(shim="C:\\moved\\mgh-guard.ts")
        self.assertEqual(code, 0)
        self.assertEqual(json.loads(line)["action"], "replaced")
        text = self.patch.read_text(encoding="utf-8")
        self.assertEqual(text.count("mgh-guard-wiring begin"), 1)  # swapped, not stacked
        self.assertIn("C:\\\\moved\\\\mgh-guard.ts", text)
        self.assertNotIn("target", text)

    def test_remove_takes_block_out(self):
        self.patch.write_text("[]\n", encoding="utf-8")
        self._run()
        code, line = self._run(remove=True)
        self.assertEqual(code, 0)
        self.assertEqual(json.loads(line)["action"], "removed")
        self.assertEqual(self.patch.read_text(encoding="utf-8"), "[]\n")

    def test_missing_profile_dir_fails_loud_no_write(self):
        ghost = self.d / "profiles" / "ghost" / "cordis.patch.yml"
        code, _ = self._run(patch=ghost)
        self.assertEqual(code, 1)
        self.assertFalse(ghost.exists())
        self.assertFalse(ghost.parent.exists())  # never invents a profile

    def test_relative_shim_is_misuse(self):
        code, _ = self._run(shim="mgh-core/dsh/mgh-guard.ts")
        self.assertEqual(code, 2)

    def test_created_from_scratch_without_existing_file(self):
        code, line = self._run(patch=self.prof / "cordis.patch.yml.new")
        # patch file may not exist yet (fresh profile) — dir exists, file created
        self.assertEqual(code, 0)
        self.assertEqual(json.loads(line)["action"], "written")


class TestDelegatesComposition(unittest.TestCase):
    """mgh profile composition face (--delegates-file): the managed block grows
    from shim-only to shim + timeout policy + named delegation instances;
    everything stays inside the markers, idempotent, and the legacy
    (flag-absent) block shape is byte-identical to before."""

    FRAGMENT = (
        "# mgh dsh named delegation instances — GENERATED by tools/gen_dsh_tiers.py\n"
        "\n"
        "- insert:\n"
        "    - id: mgh-sast-chain\n"
        "      name: '@deepseek-ai/dsh-tool-subagent'\n"
        "      config:\n"
        "        provider: spawn\n"
        "        toolName: mgh_sast_chain\n"
        "        persona: \"line one\\nline two\\n\"\n"
        "        toolFilter:\n"
        "          allow: [read, glob, grep, write]\n"
    )

    def setUp(self):
        self.m = _load()
        self.d = Path(tempfile.mkdtemp(prefix="mgh_dwc_"))
        self.prof = self.d / "profiles" / "mgh"
        self.prof.mkdir(parents=True)
        self.patch = self.prof / "cordis.patch.yml"
        self.patch.write_text("[]\n", encoding="utf-8")
        self.shim = "C:\\target\\mgh-core\\dsh\\mgh-guard.ts"
        self.frag = self.d / "delegates.patch.yml"
        self.frag.write_text(self.FRAGMENT, encoding="utf-8")

    def _run(self, delegates=None):
        argv = ["install_dsh_wiring.py",
                "--patch-file", str(self.patch),
                "--shim", self.shim]
        if delegates is not None:
            argv += ["--delegates-file", str(delegates)]
        old, sys.argv = sys.argv, argv
        out = io.StringIO()
        try:
            with contextlib.redirect_stdout(out), contextlib.redirect_stderr(io.StringIO()):
                code = self.m.main()
        except SystemExit as e:  # misuse exits inside the loader guard
            code = e.code if isinstance(e.code, int) else 1
        finally:
            sys.argv = old
        return code, out.getvalue().strip()

    def test_block_carries_shim_timeout_and_delegates(self):
        code, line = self._run(self.frag)
        self.assertEqual(code, 0, line)
        self.assertEqual(json.loads(line)["action"], "written")
        text = self.patch.read_text(encoding="utf-8")
        self.assertEqual(text.count("mgh-guard-wiring begin"), 1)
        self.assertIn("id: mgh-guard", text)
        # timeout policy rows (both shell tools, explicit key from the spike)
        self.assertIn("- id: tool-bash", text)
        self.assertIn("- id: tool-pwsh", text)
        self.assertEqual(text.count("enableRunInBackground: false"), 2)
        # delegate instance rows embedded; the generator's provenance comment
        # (build-repo path) is stripped, never shipped into a user profile
        self.assertIn("- insert:", text)
        self.assertIn("toolName: mgh_sast_chain", text)
        self.assertIn("allow: [read, glob, grep, write]", text)
        self.assertNotIn("GENERATED by tools/gen_dsh_tiers.py", text)
        self.assertTrue(text.startswith("[]"), "user content kept before the block")
        # the persona double-quoted scalar survives byte-stable (json.dumps shape:
        # `\n` is the two-char escape, valid YAML 1.2 double-quoted scalar)
        self.assertIn('"line one\\nline two\\n"', text)

    def test_double_run_present_and_stable_with_delegates(self):
        self._run(self.frag)
        before = self.patch.read_bytes()
        code, line = self._run(self.frag)
        self.assertEqual(json.loads(line)["action"], "present")
        self.assertEqual(self.patch.read_bytes(), before)

    def test_delegates_change_replaces_in_place(self):
        self._run(self.frag)
        self.frag.write_text(self.FRAGMENT + self.FRAGMENT.replace(
            "mgh-sast-chain", "mgh-sast-survey").replace("mgh_sast_chain",
                                                          "mgh_sast_survey"),
            encoding="utf-8")
        code, line = self._run(self.frag)
        self.assertEqual(json.loads(line)["action"], "replaced")
        text = self.patch.read_text(encoding="utf-8")
        self.assertEqual(text.count("mgh-guard-wiring begin"), 1)
        self.assertIn("mgh_sast_survey", text)

    def test_shim_only_block_unchanged(self):
        # legacy call shape (no flag) = byte-identical shim-only block
        self._run()
        self._run(self.frag)  # grows to the composed block
        code, line = self._run()  # back to legacy shape
        self.assertEqual(json.loads(line)["action"], "replaced")
        text = self.patch.read_text(encoding="utf-8")
        self.assertNotIn("enableRunInBackground", text)
        self.assertNotIn("mgh_sast_chain", text)

    def test_bad_fragment_shape_fails_loud(self):
        bad = self.d / "bad.yml"
        bad.write_text("[]\n", encoding="utf-8")
        code, _ = self._run(bad)
        self.assertEqual(code, 2, "not a patch-entry list → misuse, no write")
        self.assertEqual(self.patch.read_text(encoding="utf-8"), "[]\n")


class TestCreateDshProfile(unittest.TestCase):
    """tools/create_dsh_profile.py — the mgh profile skeleton: create-if-missing,
    bundle-present = present, foreign package.json = collision fail-loud."""

    def setUp(self):
        spec = importlib.util.spec_from_file_location(
            "create_dsh_profile", TOOLS / "create_dsh_profile.py")
        self.m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(self.m)
        self.d = Path(tempfile.mkdtemp(prefix="mgh_cdp_"))

    def _run(self, home):
        argv = ["create_dsh_profile.py", "--dsh-home", str(home)]
        old, sys.argv = sys.argv, argv
        out, err = io.StringIO(), io.StringIO()
        try:
            with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
                code = self.m.main()
        finally:
            sys.argv = old
        return code, out.getvalue().strip(), err.getvalue()

    def test_fresh_home_creates_both_files(self):
        code, line, err = self._run(self.d)
        self.assertEqual(code, 0, err)
        body = json.loads(line)
        self.assertEqual((body["package_json"], body["cordis_yml"]),
                         ("created", "created"))
        pkg = json.loads((self.d / "profiles" / "mgh" / "package.json")
                         .read_text(encoding="utf-8"))
        bundles = pkg["dsh"]["profile"]["bundles"]
        self.assertIn("@deepseek-ai/dsh-base", bundles)
        self.assertIn("@deepseek-ai/dsh-headless", bundles)
        self.assertEqual(pkg["dependencies"], {})

    def test_second_run_is_present_and_stable(self):
        self._run(self.d)
        pdir = self.d / "profiles" / "mgh"
        before = sorted(p.read_bytes() for p in pdir.iterdir())
        code, line, _ = self._run(self.d)
        self.assertEqual(code, 0)
        body = json.loads(line)
        self.assertEqual((body["package_json"], body["cordis_yml"]),
                         ("present", "present"))
        self.assertEqual(sorted(p.read_bytes() for p in pdir.iterdir()), before)

    def test_foreign_package_json_is_a_collision_fail_loud(self):
        prof = self.d / "profiles" / "mgh"
        prof.mkdir(parents=True)
        (prof / "package.json").write_text(
            json.dumps({"name": "mine", "dsh": {"profile": {"bundles": []}}}),
            encoding="utf-8")
        code, _, err = self._run(self.d)
        self.assertEqual(code, 1)
        self.assertIn("rename your profile", err)
        # the foreign file is NOT touched
        self.assertIn('"name": "mine"',
                      (prof / "package.json").read_text(encoding="utf-8"))

    def test_missing_home_is_misuse_with_recipe(self):
        code, _, err = self._run(self.d / "nope")
        self.assertEqual(code, 2)
        self.assertIn("recipe", err)

    def test_relative_home_is_misuse(self):
        code, _, _ = self._run("relative/path")
        self.assertEqual(code, 2)


class TestDshFaceLayout(unittest.TestCase):
    """Repo-side invariants for the dsh face (co-location contract the shim relies on):
    the canonical guard lives in core/scripts AND its sibling source tree mirrors exist."""

    ROOT = HERE.parent

    def test_core_guard_next_to_dsh_shim_source(self):
        self.assertTrue((self.ROOT / "core" / "scripts" / "block_adhoc_scripts.py").is_file())
        self.assertTrue((self.ROOT / "releases" / "dsh" / "plugins" / "mgh-guard.ts").is_file())

    def test_install_scripts_declare_dsh_dialect(self):
        sh = (self.ROOT / "install.sh").read_text(encoding="utf-8")
        ps = (self.ROOT / "install.ps1").read_text(encoding="utf-8")
        self.assertIn("--dsh", sh)
        self.assertIn("install_dsh_wiring.py", sh)
        self.assertIn("dsh", ps)
        self.assertIn("install_dsh_wiring.py", ps)

    def test_install_scripts_place_and_check_skills(self):
        # add-mgh-dsh-command-surface 4.1/4.2: skills placement + self-check present on
        # both faces, and the skills check precedes the ENFORCE_HOOK gate (placement is
        # unconditional; --no-enforce-hook skips wiring only).
        sh = (self.ROOT / "install.sh").read_text(encoding="utf-8")
        ps = (self.ROOT / "install.ps1").read_text(encoding="utf-8")
        for cmd in ("mgh-sdr", "mgh-sast", "mgh-init", "mgh-sra", "mgh-srr"):
            self.assertIn(cmd, sh)
            self.assertIn(cmd, ps)
        self.assertIn(".dsh/skills", sh)
        self.assertIn(".dsh\\skills", ps)
        gate = 'if [[ "$ENFORCE_HOOK"'
        i_dsh = sh.index('if [[ "$PLATFORM" == "dsh" ]]')
        i_check = sh.index("dsh skills self-check")
        self.assertLess(i_dsh, i_check)
        self.assertLess(i_check, sh.rindex(gate),
                        "skills self-check must not hide behind the dsh --no-enforce-hook gate")

    def test_install_scripts_compose_fanout_assets(self):
        # add-mgh-dsh-subagent-fanout 5.1: both faces generate tier mounts + the delegates
        # fragment, create the mgh skeleton, and embed delegates in the wiring call; the
        # 'sole existing profile' inference is gone (mgh is the fixed composition face).
        sh = (self.ROOT / "install.sh").read_text(encoding="utf-8")
        ps = (self.ROOT / "install.ps1").read_text(encoding="utf-8")
        for token in ("gen_dsh_tiers.py", "create_dsh_profile.py", "--delegates-file"):
            self.assertIn(token, sh)
            self.assertIn(token, ps)
        self.assertIn("--check", sh)  # tier<->agents 1:1 self-check
        self.assertIn("--check", ps)
        self.assertNotIn("sole existing dsh profile", sh)
        self.assertNotIn("sole existing dsh profile", ps)


class TestDshSkillsInstall(unittest.TestCase):
    """End-to-end: run install.sh --dsh into a scratch target with an isolated
    DSH_HOME, assert the five shells land in <target>/.dsh/skills/, tier mounts +
    delegates fragment are generated under <target>/mgh-core/dsh/, the mgh profile
    skeleton + composition block is wired (shim + delegates), user profiles stay
    untouched, reinstall refreshes idempotently, and a deleted shell is reported by
    the fail-soft self-check. Skipped when bash is unavailable."""

    ROOT = HERE.parent
    COMMANDS = ("mgh-sdr", "mgh-sast", "mgh-init", "mgh-sra", "mgh-srr")
    TIERS = ("scout", "t1", "t2", "t3", "sdr")

    def setUp(self):
        import shutil
        self.bash = shutil.which("bash")
        if not self.bash:
            self.skipTest("bash not on PATH")
        import tempfile
        self.d = Path(tempfile.mkdtemp(prefix="mgh_dsh_sk_"))
        self.target = self.d / "proj"
        self.target.mkdir()
        self.dsh_home = self.d / "dshhome"
        # a USER-owned profile that must survive untouched (mgh is the sole composition face)
        (self.dsh_home / "profiles" / "web").mkdir(parents=True)
        (self.dsh_home / "profiles" / "web" / "cordis.patch.yml").write_text("[]\n", encoding="utf-8")

    def _install(self, extra=()):
        import os, subprocess
        env = dict(os.environ, DSH_HOME=str(self.dsh_home))
        return subprocess.run(
            [self.bash, "install.sh", "--dsh", *extra, str(self.target)],
            cwd=str(self.ROOT), env=env, capture_output=True, text=True,
            encoding="utf-8", errors="replace", timeout=300)

    def _skill(self, cmd):
        return self.target / ".dsh" / "skills" / cmd / "SKILL.md"

    def test_five_shells_placed_and_clean_selfcheck(self):
        r = self._install()
        self.assertEqual(r.returncode, 0, r.stderr[-800:])
        self.assertIn("dsh skills placed", r.stdout)
        for cmd in self.COMMANDS:
            text = self._skill(cmd).read_text(encoding="utf-8")
            self.assertIn(f"name: {cmd}", text)
            self.assertIn("user-invocable: true", text)
        self.assertEqual(sorted(p.name for p in (self.target / ".dsh" / "skills").iterdir()),
                         sorted(self.COMMANDS))

    def test_tiers_delegates_and_mgh_profile_wired(self):
        r = self._install()
        self.assertEqual(r.returncode, 0, r.stderr[-800:])
        self.assertIn("dsh tier mounts current", r.stdout)
        self.assertIn("wired mgh composition block", r.stdout)
        dsh = self.target / "mgh-core" / "dsh"
        for t in self.TIERS:
            self.assertTrue((dsh / "tiers" / f"{t}.yml").is_file(), f"tier mount {t} missing")
        delegates = (dsh / "delegates.patch.yml").read_text(encoding="utf-8")
        self.assertIn("mgh_sast_deepdive", delegates)
        patch = (self.dsh_home / "profiles" / "mgh" / "cordis.patch.yml").read_text(encoding="utf-8")
        self.assertIn("mgh-guard-wiring begin", patch)
        self.assertIn("mgh_sast_deepdive", patch)   # delegates embedded in the managed block
        self.assertIn("enableRunInBackground", patch)  # timeout policy rows composed too
        pkg = json.loads((self.dsh_home / "profiles" / "mgh" / "package.json")
                         .read_text(encoding="utf-8"))
        self.assertIn("@deepseek-ai/dsh-headless",
                      pkg["dsh"]["profile"]["bundles"])
        # the user's own 'web' profile keeps zero mgh wiring
        self.assertEqual((self.dsh_home / "profiles" / "web" / "cordis.patch.yml")
                         .read_text(encoding="utf-8"), "[]\n")

    def test_reinstall_refreshes_without_duplicates(self):
        self._install()
        marker = self._skill("mgh-sra").read_text(encoding="utf-8") + "\n<!-- touched -->"
        self._skill("mgh-sra").write_text(marker, encoding="utf-8")
        r2 = self._install()
        self.assertEqual(r2.returncode, 0, r2.stderr[-800:])
        self.assertNotIn("touched", self._skill("mgh-sra").read_text(encoding="utf-8"))
        self.assertEqual(len(list((self.target / ".dsh" / "skills").iterdir())), 5)
        patch = (self.dsh_home / "profiles" / "mgh" / "cordis.patch.yml").read_text(encoding="utf-8")
        self.assertEqual(patch.count("mgh-guard-wiring begin"), 1)  # block swapped, not stacked
        for t in self.TIERS:  # tier mounts byte-stable across reinstall
            before = (self.target / "mgh-core" / "dsh" / "tiers" / f"{t}.yml").read_bytes()
            self._install()
            self.assertEqual((self.target / "mgh-core" / "dsh" / "tiers" / f"{t}.yml")
                             .read_bytes(), before)

    def test_non_mgh_profile_name_is_rejected(self):
        r = self._install(extra=("--dsh-profile", "web"))
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("not honored", r.stderr)
        self.assertFalse((self.dsh_home / "profiles" / "web" / "cordis.patch.yml")
                         .read_text(encoding="utf-8").startswith("#"))

    def test_no_enforce_hook_still_places_skills(self):
        # shells ≠ enforcement: --no-enforce-hook skips the composition block only;
        # placement, tier generation and the mgh skeleton all still run.
        t2 = self.d / "proj2"
        t2.mkdir()
        import os, subprocess
        env = dict(os.environ, DSH_HOME=str(self.dsh_home))
        r2 = subprocess.run(
            [self.bash, "install.sh", "--dsh", "--no-enforce-hook", str(t2)],
            cwd=str(self.ROOT), env=env, capture_output=True, text=True,
            encoding="utf-8", errors="replace", timeout=300)
        self.assertEqual(r2.returncode, 0, r2.stderr[-800:])
        self.assertIn("dsh skills placed", r2.stdout)
        self.assertTrue((t2 / ".dsh" / "skills" / "mgh-sdr" / "SKILL.md").is_file())
        self.assertTrue((t2 / "mgh-core" / "dsh" / "tiers" / "sdr.yml").is_file())
        self.assertTrue((self.dsh_home / "profiles" / "mgh" / "package.json").is_file())
        patch_file = self.dsh_home / "profiles" / "mgh" / "cordis.patch.yml"
        patch = patch_file.read_text(encoding="utf-8") if patch_file.is_file() else ""
        self.assertNotIn("mgh-guard-wiring begin", patch)  # wiring skipped (file not created)

    def _run_skills_selfcheck(self, target):
        """Execute install.sh's skills self-check block verbatim (textually extracted)
        against a mutated placed tree — proves the detection branches without needing
        a half-failed cp."""
        import re
        import subprocess
        sh = (self.ROOT / "install.sh").read_text(encoding="utf-8")
        m = re.search(r"(_skill_missing=\(\).*?)\n  fi\n", sh, re.S)
        self.assertIsNotNone(m, "install.sh skills self-check block not found")
        snippet = m.group(1) + "\n  fi\n"
        return subprocess.run(
            [self.bash, "-c", f'TARGET="{target.as_posix()}";\n{snippet}'],
            capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=60)

    def test_selfcheck_reports_missing_and_broken_shells(self):
        import shutil
        self._install()
        shutil.rmtree(self.target / ".dsh" / "skills" / "mgh-srr")
        bad = self._skill("mgh-sra")
        bad.write_text(bad.read_text(encoding="utf-8").replace("name: mgh-sra\n", "name: nope\n"),
                       encoding="utf-8")
        r = self._run_skills_selfcheck(self.target)
        self.assertEqual(r.returncode, 0)  # fail-SOFT posture (CI enforces separately)
        self.assertIn("mgh-srr (missing)", r.stderr)
        self.assertIn("mgh-sra (frontmatter", r.stderr)


